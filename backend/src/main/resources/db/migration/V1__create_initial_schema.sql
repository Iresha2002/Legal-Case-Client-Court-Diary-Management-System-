-- Initial schema based on the approved ER diagram.
-- Once applied by Flyway, make future changes in a new migration.

-- Role names include Senior Lawyer, Junior Lawyer, Clerk, and Admin.
CREATE TABLE roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL,
    email varchar NOT NULL,
    password_hash varchar NOT NULL,
    role_id bigint NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

CREATE INDEX idx_users_role_id ON users(role_id);

CREATE TABLE clients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar NOT NULL,
    nic_or_passport varchar NOT NULL,
    phone varchar,
    email varchar,
    address text,
    CONSTRAINT uk_clients_nic_or_passport UNIQUE (nic_or_passport)
);

CREATE TABLE cases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_number varchar NOT NULL,
    case_type varchar NOT NULL,
    court_name varchar NOT NULL,
    judge varchar,
    court_room varchar,
    defendant varchar,
    status varchar NOT NULL,
    lifecycle_status varchar NOT NULL,
    client_id bigint NOT NULL,
    CONSTRAINT uk_cases_case_number UNIQUE (case_number),
    CONSTRAINT fk_cases_client FOREIGN KEY (client_id) REFERENCES clients(id),
    CONSTRAINT ck_cases_status CHECK (status IN ('ongoing', 'past')),
    CONSTRAINT ck_cases_lifecycle_status CHECK (lifecycle_status IN ('Draft', 'Filed', 'Active', 'Closed'))
);

CREATE TABLE case_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id bigint NOT NULL,
    user_id bigint NOT NULL,
    assignment_type varchar NOT NULL,
    CONSTRAINT fk_case_assignments_case FOREIGN KEY (case_id) REFERENCES cases(id),
    CONSTRAINT fk_case_assignments_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_case_assignments_type CHECK (assignment_type IN ('lead', 'support'))
);

CREATE TABLE hearings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id bigint NOT NULL,
    hearing_date date NOT NULL,
    hearing_time time NOT NULL,
    court_room_no varchar,
    judge varchar,
    purpose text,
    CONSTRAINT fk_hearings_case FOREIGN KEY (case_id) REFERENCES cases(id)
);

CREATE TABLE diary_notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id bigint NOT NULL,
    hearing_id bigint,
    note_text text NOT NULL,
    written_by bigint NOT NULL,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_diary_notes_case FOREIGN KEY (case_id) REFERENCES cases(id),
    CONSTRAINT fk_diary_notes_hearing FOREIGN KEY (hearing_id) REFERENCES hearings(id),
    CONSTRAINT fk_diary_notes_author FOREIGN KEY (written_by) REFERENCES users(id)
);

-- Type names include Pleadings, Evidence, Orders, and Motions.
CREATE TABLE document_types (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar NOT NULL
);

CREATE TABLE documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id bigint NOT NULL,
    document_type_id bigint NOT NULL,
    file_name varchar NOT NULL,
    file_size bigint NOT NULL,
    storage_path varchar NOT NULL,
    uploaded_by bigint NOT NULL,
    uploaded_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_documents_case FOREIGN KEY (case_id) REFERENCES cases(id),
    CONSTRAINT fk_documents_type FOREIGN KEY (document_type_id) REFERENCES document_types(id),
    CONSTRAINT fk_documents_uploader FOREIGN KEY (uploaded_by) REFERENCES users(id),
    CONSTRAINT ck_documents_file_size CHECK (file_size >= 0)
);

CREATE TABLE activity_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity varchar NOT NULL,
    user_id bigint NOT NULL,
    date date NOT NULL,
    time time NOT NULL,
    case_id bigint,
    old_value text,
    new_value text,
    CONSTRAINT fk_activity_history_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_activity_history_case FOREIGN KEY (case_id) REFERENCES cases(id),
    CONSTRAINT ck_activity_history_activity CHECK (activity IN ('view', 'add', 'edit', 'delete', 'upload', 'download'))
);

-- Index foreign keys for joins and parent record checks.
CREATE INDEX idx_cases_client_id ON cases(client_id);
CREATE INDEX idx_case_assignments_case_id ON case_assignments(case_id);
CREATE INDEX idx_case_assignments_user_id ON case_assignments(user_id);
CREATE INDEX idx_hearings_case_id ON hearings(case_id);
CREATE INDEX idx_diary_notes_case_id ON diary_notes(case_id);
CREATE INDEX idx_diary_notes_hearing_id ON diary_notes(hearing_id);
CREATE INDEX idx_diary_notes_written_by ON diary_notes(written_by);
CREATE INDEX idx_documents_case_id ON documents(case_id);
CREATE INDEX idx_documents_document_type_id ON documents(document_type_id);
CREATE INDEX idx_documents_uploaded_by ON documents(uploaded_by);
CREATE INDEX idx_activity_history_user_id ON activity_history(user_id);
CREATE INDEX idx_activity_history_case_id ON activity_history(case_id);
